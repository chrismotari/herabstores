/**
 * Builds the storefront's theme stylesheet.
 *
 *   source: theme/theme.full.css  (the full theme CSS: Bootstrap 4 + Font Awesome + theme; edit this)
 *   output: public/theme/css/theme.css  (generated, gitignored; imported by src/app/layout.tsx)
 *
 * PurgeCSS keeps only rules whose classes appear in src/**. Classes that are added at
 * runtime or built from strings must be in SAFELIST below, or they lose their styles.
 * Sections between "purgecss start ignore" and "purgecss end ignore" comments in the source
 * are kept whole (the Flaticon icon font: its base rule is an attribute selector).
 * Runs automatically before `pnpm dev` and `pnpm build`.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PurgeCSS } from "purgecss";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "theme/theme.full.css");
const output = join(root, "public/theme/css/theme.css");

const SAFELIST = {
  standard: [
    // Toggled by our client components
    "sticky-menu", "mobile-menu-visible", "active", "show", "open", "collapsed",
    // Form validation / feedback states
    "is-invalid", "is-valid", "invalid-feedback", "valid-feedback", "was-validated", "disabled",
    // Elements React renders without a class (html/body defaults are kept by PurgeCSS)
    "sr-only",
  ],
  deep: [/^alert/, /^text-/, /^bg-/, /^btn/],
  greedy: [
    /minicart/, /mobile-menu/, /menu-backdrop/, /sticky/,
  ],
};

const [result] = await new PurgeCSS().purge({
  content: [join(root, "src/**/*.{ts,tsx}")],
  css: [source],
  safelist: SAFELIST,
  fontFace: true,
  keyframes: true,
  variables: false,
  // Keep class-like tokens in template strings, e.g. `discount-item${x ? " style-two" : ""}`
  defaultExtractor: (content) => content.match(/[A-Za-z0-9_-]+/g) ?? [],
});

mkdirSync(dirname(output), { recursive: true });
const header = "/* GENERATED by scripts/build-theme-css.mjs from theme/theme.full.css. Do not edit. */\n";
writeFileSync(output, header + result.css);

const kb = (n) => `${Math.round(n / 1024)} KB`;
console.log(`theme.css: ${kb(readFileSync(source).length)} -> ${kb(result.css.length)}`);
